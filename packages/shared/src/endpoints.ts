/** Schema references are immutable contract metadata, not controller authorization. */
function endpoint<
  const M extends string,
  const P extends string,
  R extends z.ZodType,
  I extends z.ZodType = typeof p.emptyInputSchema,
  Q extends z.ZodType = typeof p.emptyInputSchema,
>(method: M, path: P, response: R, input?: I, query?: Q, headers?: z.ZodType) {
  const params = Object.fromEntries(
    [...path.matchAll(/:([A-Za-z]+)/g)].map(([, key = '']) => [
      key,
      key === 'slug'
        ? p.slugSchema
        : key === 'verificationCode'
          ? e.verificationCodeSchema
          : p.uuidSchema,
    ]),
  );
  return {
    method,
    path,
    response,
    input: (input ?? p.emptyInputSchema) as I,
    query: (query ?? p.emptyInputSchema) as Q,
    params: z.strictObject(params),
    headers,
  } as const;
}
